"""Requirements layer of the kosif-superpowers skill: every power names what it needs, every name is registered."""
from __future__ import annotations

import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / ".claude" / "skills" / "kosif-superpowers"
SCRIPT = SKILL / "scripts" / "requirements.py"
REG = json.loads((SKILL / "data" / "requirements.json").read_text(encoding="utf-8"))
KEYS = {k for k in REG if not k.startswith("_")}
KINDS = {"bin", "pip", "npm", "apt", "key", "service", "os", "font", "model"}


def run(*args):
    return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True, timeout=120)


class RequirementsTest(unittest.TestCase):
    def test_registry_entries_are_complete_and_bilingual(self):
        for k in KEYS:
            v = REG[k]
            with self.subTest(req=k):
                self.assertIn(v["kind"], KINDS)
                for f in ("install", "ar", "en"):
                    self.assertTrue(v.get(f), f"{k}: missing {f}")
                self.assertRegex(v["ar"], r"[؀-ۿ]")
                self.assertIsInstance(v.get("patterns"), list)

    def test_every_record_has_registered_requires(self):
        for f in sorted((SKILL / "data" / "powers").glob("*.json")):
            for rec in json.loads(f.read_text(encoding="utf-8")):
                with self.subTest(power=rec["id"]):
                    self.assertIn("requires", rec)
                    self.assertTrue(set(rec["requires"]) <= KEYS, rec["requires"])

    def test_derive_is_stable(self):
        proc = run("derive", "--check")
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def test_plan_json_lists_powers_and_requirements(self):
        proc = run("plan", "Arabic reel with voice-over and synced captions", "--json", "--limit", "8")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        data = json.loads(proc.stdout)
        self.assertTrue(data["powers"])
        for item in data["requirements"]:
            self.assertIn(item["key"], KEYS)
            self.assertIn(item["state"], {"present", "missing", "unknown"})

    def test_keys_are_never_printed_by_value(self):
        src = SCRIPT.read_text(encoding="utf-8")
        self.assertNotIn("print(os.environ", src)

    def test_index_is_current(self):
        text = (SKILL / "references" / "requirements.md").read_text(encoding="utf-8")
        self.assertIn("generated by scripts/requirements.py index", text)
        for k in KEYS:
            self.assertIn(f"`{k}`", text)


if __name__ == "__main__":
    unittest.main()
