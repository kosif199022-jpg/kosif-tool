"""End-to-end local rendering smoke test on synthetic, entirely self-created media."""
import importlib.util
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/".claude"/"skills"/"kosif-superpowers"/"scripts"
sys.path.insert(0,str(SRC))
import cinematic_cut_planner as cut
import cinematic_broll_render as film


def ff(*args):
    subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-nostdin","-y",*map(str,args)],
                   capture_output=True,check=True,timeout=90)


class RenderingTests(unittest.TestCase):
    def test_rejects_gaps(self):
        edl={"video":{"frame_count":60},"audio":{"preserve_original":True,"audio_editing_allowed":False},
             "production_ready":True,"blockers":[],"scenes":[{"start_frame":1,"end_frame_exclusive":60,
             "rights_status":"verified"}]}
        with self.assertRaisesRegex(ValueError,"gap"):
            film.check_scene_timeline(edl)

    def test_camera_is_dynamic(self):
        self.assertIn("zoompan",film.camera_filter("slow_push_in",30,30,180,320))
        self.assertNotEqual(film.camera_filter("gentle_pan_left",30,30,180,320),
                            film.camera_filter("gentle_pan_right",30,30,180,320))

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),"FFmpeg not installed")
    def test_real_render_and_bitstream_copy(self):
        with tempfile.TemporaryDirectory(prefix="kosif_film_test_") as root:
            root=Path(root)
            video=root/"self_created_footage.mp4"
            audio=root/"original.wav"
            ff("-f","lavfi","-i","testsrc2=size=480x270:rate=30",
               "-t","2.5","-an","-c:v","libx264","-pix_fmt","yuv420p",video)
            ff("-f","lavfi","-i","sine=frequency=550:sample_rate=48000",
               "-t","2.0","-c:a","pcm_s16le",audio)
            clip={"id":"original_001","path":video.name,"duration":2.5,
                  "width":480,"height":270,"license_verified":True,
                  "license_document":"Synthetic clip generated by this test, no third-party rights",
                  "reviewed_frames":3,"contains_text":False,
                  "contains_excluded_people":False,"is_moving_video":True,
                  "tags":["مكة","مدينة"],"sha256":film.sha256(video)}
            manifest=root/"footage.json"
            manifest.write_text(json.dumps([clip],ensure_ascii=False),encoding="utf-8")
            words=[{"word":"مكة","start":.1,"end":.3,"emphasis":True},
                   {"word":"مدينة","start":1.1,"end":1.5}]
            edl=cut.build(words,[clip],2.0,30)
            self.assertTrue(edl["production_ready"])
            self.assertEqual(len(edl["scenes"]),2)
            p=root/"timeline.json"
            p.write_text(json.dumps(edl,ensure_ascii=False),encoding="utf-8")
            out=root/"master.mkv"
            result=film.render(p,manifest,audio,out,180,320)
            self.assertEqual(result["video_frames"],60)
            self.assertTrue(result["audio_stream_copied"])
            self.assertEqual(result["audio_codec"],"pcm_s16le")
            self.assertTrue(out.exists())
            self.assertEqual(result["audio_original_sha256"],film.sha256(audio))
            # An authentic unmodified audio stream must survive muxing
            def audio_hash(p):
                v=subprocess.run(["ffmpeg","-v","error","-i",str(p),"-map","0:a:0",
                                  "-c:a","copy","-f","hash","-hash","SHA256","-"],
                                 capture_output=True,text=True,check=True,timeout=30)
                return v.stdout.strip()
            self.assertEqual(audio_hash(audio),audio_hash(out))
            with self.assertRaises(FileExistsError):
                film.render(p,manifest,audio,out,180,320)
            clip["sha256"]="0"*64
            manifest.write_text(json.dumps([clip],ensure_ascii=False),encoding="utf-8")
            with self.assertRaisesRegex(ValueError,"SHA256"):
                film.verify_footage(edl,[clip],root)


if __name__=="__main__":
    unittest.main()
