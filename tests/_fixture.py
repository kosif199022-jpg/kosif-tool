def record(style_id: str, **overrides) -> dict:
    """A complete schema record with sensible nulls, overridden per test."""
    rec = {
        "id": style_id,
        "name": style_id,
        "name_ar": None,
        "origin": "PromptsMotion",
        "type": "Prompt",
        "category": [],
        "creator": "@demo",
        "creator_url": None,
        "page": f"https://example.com/{style_id}",
        "video": None,
        "poster": None,
        "aspect": None,
        "aspect_label": None,
        "rank": None,
        "published": None,
        "model": None,
        "effort": None,
        "tech": [],
        "source_prompt_words": None,
        "difficulty": None,
        "duration_s": None,
        "stack": [],
        "keywords": [],
        "summary_ar": None,
        "summary_en": None,
        "brief": None,
        "skill": f"styles/{style_id}/SKILL.md",
        "playbooks": [],
    }
    rec.update(overrides)
    return rec


