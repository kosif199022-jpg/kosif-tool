def brief_for(style_id: str) -> dict:
    b = {k: f"{k} of {style_id}" for k in BRIEF_KEYS}
    b.update({"id": style_id, "duration_s": 12, "aspect": "16:9", "difficulty": 3, "stack": ["Remotion"], "keywords": ["bars"],
              "scenes_en": ["intro", "bars", "outro"], "scenes_ar": ["مقدمة", "أعمدة", "خاتمة"], "facts_from_source": [], "assumptions_en": []})
    return b


def write_json(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def build_repo(root: Path, records: list[dict] | None = None, briefs: dict | None = None, starters: tuple[str, ...] = ("html-canvas",)) -> Path:
    """Write a complete, validator-clean mini repository under *root*."""
    root = Path(root)
    records = records if records is not None else make_records()
    briefs = briefs if briefs is not None else {PM_A: brief_for(PM_A)}
    (root / "catalog").mkdir(parents=True, exist_ok=True)
    write_json(root / "catalog" / "styles.json", records)
    write_json(root / "catalog" / "categories.json", CATEGORIES)
    write_json(root / "catalog" / "prompts_motion.json", [r for r in records if r.get("origin") == "PromptsMotion"])
    write_json(root / "catalog" / "briefs.json", briefs)
    write_json(root / "catalog" / "playbooks.json", [
        {"key": c["key"], "title_ar": c["ar"], "title_en": c["en"], "path": c["playbook"], "excerpt": "demo"} for c in CATEGORIES
    ])
    write_json(root / "catalog" / "meta.json", {"total": len(records)})
    for c in CATEGORIES:
        p = root / c["playbook"]
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(f"# {c['en']} — {c['ar']}\n\nDemo playbook.\n", encoding="utf-8")
    lines = ["# Demo index", ""]
    for r in records:
        d = root / "styles" / r["id"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "SKILL.md").write_text(f"---\nname: {r['id']}\n---\n# {r['name']}\n", encoding="utf-8")
        write_json(d / "STYLE.json", r)
        if r.get("brief"):
            (d / "BRIEF.md").write_text(f"# Brief for {r['id']}\n\nمقترح إبداعي تجريبي.\n", encoding="utf-8")
        lines.append(f"- [{r['id']}](styles/{r['id']}/SKILL.md) — {r['name']} — [reference]({r['page']})")
    (root / "STYLE_INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    tdir = root / "templates"
    tdir.mkdir(exist_ok=True)
    for name in TEMPLATE_FILES:
        src = REAL_ROOT / "templates" / name
        if src.exists():
            shutil.copyfile(src, tdir / name)
    for name in starters:
        sdir = root / "starters" / name
        sdir.mkdir(parents=True, exist_ok=True)
        (sdir / "index.html").write_text("<!doctype html><title>demo starter</title>\n", encoding="utf-8")
        (sdir / "node_modules").mkdir(exist_ok=True)
        (sdir / "node_modules" / "junk.txt").write_text("should not be copied\n", encoding="utf-8")
    return root


def _env() -> dict:
    env = dict(os.environ)
    env["PYTHONIOENCODING"] = "utf-8"
    env.pop("KOSIF_ROOT", None)
    return env


def run_kosif(*args: str, root: Path | None = None, cwd: Path | None = None) -> subprocess.CompletedProcess:
    cmd = [sys.executable, str(KOSIF)]
    if root is not None:
        cmd += ["--root", str(root)]
    cmd += [str(a) for a in args]
    return subprocess.run(cmd, cwd=str(cwd or Path.cwd()), capture_output=True, text=True, encoding="utf-8", env=_env(), timeout=120)


def run_validate(root: Path, *args: str) -> subprocess.CompletedProcess:
    cmd = [sys.executable, str(VALIDATE), "--root", str(root)] + [str(a) for a in args]
    return subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", env=_env(), timeout=300)


def real_catalog():
    """(records, categories) from the real repo, or (None, reason) when it cannot be read right now."""
    try:
        records = json.loads((REAL_ROOT / "catalog" / "styles.json").read_text(encoding="utf-8"))
        categories = json.loads((REAL_ROOT / "catalog" / "categories.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, f"catalog unreadable (probably mid-regeneration): {exc}"
    if not isinstance(records, list) or not records:
        return None, "catalog/styles.json is not a non-empty list (probably mid-regeneration)"
    return (records, categories), ""
