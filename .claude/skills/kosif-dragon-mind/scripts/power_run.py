#!/usr/bin/env python3
"""Run one method card as a real program and prove it: power_run.py ARTIFACT POWER_ID TASK

Loads every ``runners/fam_*.py`` module, finds the function registered for POWER_ID, runs it in a
fresh work folder next to ARTIFACT (``<stem>.work/``) and writes ARTIFACT as JSON: the checks with
measured and expected values, and the SHA-256 of every output. Exit 0 only when every check passed
and at least one non-empty output exists; exit 3 otherwise (no runner, a failed check, an error).

``power_run.py --build [--jobs N]`` runs every registered card once in a scratch folder and writes
``kosif-superpowers/data/black_dragon_adapters_powers_mind.json`` with only the cards that passed,
plus ``runners/_build_report.json`` (passed, failed with reason, gaps).
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import sys
import tempfile
import time
import traceback
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNNERS = HERE.parent / "runners"
REPO = HERE.parents[3]
REGISTRY_FILE = REPO / ".claude/skills/kosif-superpowers/data/black_dragon_adapters_powers_mind.json"
SCRIPT_REL = ".claude/skills/kosif-dragon-mind/scripts/power_run.py"
sys.path.insert(0, str(RUNNERS))
import _harness as H  # noqa: E402

_LOADED = False
GAPS: dict = {}
OWNER: dict = {}
BROKEN: dict = {}


def load_all() -> dict:
    global _LOADED
    if not _LOADED:
        for path in sorted(RUNNERS.glob("fam_*.py")):
            before = set(H.REGISTRY)
            spec = importlib.util.spec_from_file_location(path.stem, path)
            mod = importlib.util.module_from_spec(spec)
            try:
                spec.loader.exec_module(mod)
            except Exception as exc:  # one broken module must not hide every other family
                for cid in set(H.REGISTRY) - before:
                    del H.REGISTRY[cid]
                BROKEN[path.name] = "%s: %s" % (type(exc).__name__, str(exc)[:200])
                continue
            for cid in set(H.REGISTRY) - before:
                OWNER[cid] = path.name
            GAPS.update(getattr(mod, "GAPS", {}))
        _LOADED = True
    return H.REGISTRY


def run_card(card_id: str, task: str, wd: Path) -> dict:
    card_id = card_id.split(":", 1)[1] if card_id.startswith("power:") else card_id
    fn = load_all().get(card_id)
    res = {"entry": "power:" + card_id, "task": task, "runner": OWNER.get(card_id)}
    if fn is None:
        res.update(verdict="no-runner", reason=GAPS.get(card_id, "no real runner registered"))
        return res
    wd.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    try:
        checks, outputs = fn(task, wd)
    except Exception as exc:  # the card's program failed: report, never pretend
        res.update(verdict="error", reason="%s: %s" % (type(exc).__name__, str(exc)[:300]),
                   trace=traceback.format_exc()[-800:])
        return res
    outs = []
    for o in outputs or []:
        o = Path(o)
        outs.append({"path": str(o), "bytes": o.stat().st_size if o.is_file() else 0,
                     "sha256": H.sha(o) if o.is_file() else None})
    ok_out = any(o["bytes"] > 0 for o in outs)
    ok_checks = bool(checks) and all(c["passed"] for c in checks)
    res.update(verdict="executed" if ok_out and ok_checks else "failed", seconds=round(time.time() - t0, 3),
               checks=checks, outputs=outs,
               rule="executed = the card's program ran, every known-answer check passed, outputs hashed")
    if not ok_out:
        res["reason"] = "no non-empty output"
    elif not ok_checks:
        res["reason"] = "failed checks: " + ", ".join(c["check"] for c in checks if not c["passed"]) if checks else "no checks"
    return res


def _build_one(card_id: str) -> dict:
    with tempfile.TemporaryDirectory(prefix="pr-") as tmp:
        r = run_card(card_id, "اعمل فيديو موشن عربي قصير", Path(tmp) / "work")
    return {"id": card_id, "verdict": r["verdict"], "reason": r.get("reason"), "runner": r.get("runner"),
            "seconds": r.get("seconds")}


def build(jobs: int = 4) -> dict:
    ids = sorted(load_all())
    with ProcessPoolExecutor(max_workers=jobs) as ex:
        rows = list(ex.map(_build_one, ids))
    passed = [r["id"] for r in rows if r["verdict"] == "executed"]
    adapters = {"power:" + cid: {"script": SCRIPT_REL, "args": ["{artifact}", cid, "{task}"],
                                 "why": "real runner (%s): the card's method as a program with known-answer checks"
                                        % OWNER.get(cid)} for cid in passed}
    REGISTRY_FILE.write_text(json.dumps({"_comment": "Generated by dragon_mind power_run.py --build: only cards whose "
                                         "program passed every known-answer check here.", "adapters": adapters},
                                        ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    report = {"registered": len(ids), "passed": len(passed), "failed": [r for r in rows if r["verdict"] != "executed"],
              "gaps": dict(sorted(GAPS.items())), "broken_modules": BROKEN, "by_module": {}}
    for r in rows:
        m = report["by_module"].setdefault(r["runner"], {"passed": 0, "failed": 0})
        m["passed" if r["verdict"] == "executed" else "failed"] += 1
    (RUNNERS / "_build_report.json").write_text(json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return report


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv[:1] == ["--build"]:
        jobs = int(argv[argv.index("--jobs") + 1]) if "--jobs" in argv else 4
        rep = build(jobs)
        print(json.dumps({k: (len(v) if isinstance(v, (list, dict)) and k != "by_module" else v)
                          for k, v in rep.items()}, ensure_ascii=False, indent=1))
        return 0
    if len(argv) != 3:
        print("usage: power_run.py ARTIFACT POWER_ID TASK | --build [--jobs N]", file=sys.stderr)
        return 2
    artifact = Path(argv[0])
    wd = artifact.parent / (artifact.stem + ".work")
    if wd.exists():
        shutil.rmtree(wd)
    res = run_card(argv[1], argv[2], wd)
    artifact.parent.mkdir(parents=True, exist_ok=True)
    artifact.write_text(json.dumps(res, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return 0 if res["verdict"] == "executed" else 3


if __name__ == "__main__":
    sys.exit(main())
