#!/usr/bin/env python3
"""Build data/black_dragon_adapters_powers.json: Black Dragon adapters for powers whose cited proof code runs green.

    build_black_dragon_power_adapters.py [--workers 4] [--slow-limit 120] [--job DIR]
    build_black_dragon_power_adapters.py --check

Build mode RUNS every candidate power once through _black_dragon_power.py (shared cache, so each
distinct test file or tool suite runs once) and keeps ONLY the powers that passed, finished under
the slow limit and are not refused. Every other candidate is listed under `excluded` with its
reason. A candidate is a power with at least one `kosif-tool/` proof that names a code file in this
repository. The output is deterministic: sorted keys, no timestamps, no durations (only a bucketed
`slow` reason), and each included entry pins the SHA-256 of every proof file it was verified on.

--check runs nothing. It fails (exit 1) when the file is not in canonical form, when the candidate
set changed (a power gained or lost a code proof), or when a proof file of an included power has
changed since it was verified (re-run the build to re-verify).
"""
from __future__ import annotations
import argparse
import concurrent.futures as futures
import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
SKILL = SCRIPTS.parent
REPO = SKILL.parents[2]
OUT = SKILL / "data" / "black_dragon_adapters_powers.json"
RUNNER = SCRIPTS / "_black_dragon_power.py"
sys.path.insert(0, str(SCRIPTS))
import _black_dragon_power as power_mod  # noqa: E402

SCHEMA = "kosif.black-dragon.power-adapters.v1"
COMMENT = ("Generated by scripts/build_black_dragon_power_adapters.py from a real run: each power below cited "
           "code in this repository as proof, and that code (its test file, its tool runner or its --self-test) "
           "ran and passed here. Re-run the build after changing a proof file; --check detects drift. "
           "The reviewed black_dragon_adapters.json wins on any key collision.")
ALL_CODE = (".py", ".js", ".mjs", ".cjs", ".sh")


def all_powers() -> list[dict]:
    rows = []
    for path in sorted(power_mod.POWERS.glob("*.json")):
        obj = json.loads(path.read_text(encoding="utf-8"))
        rows += obj if isinstance(obj, list) else obj.get("powers", [])
    return [r for r in rows if isinstance(r, dict) and r.get("id")]


def any_code_proof(row: dict) -> list[str]:
    """Proof references to existing code files of any language (wider than the runnable set)."""
    out = []
    for ref in row.get("proof") or []:
        if not isinstance(ref, str) or not ref.startswith("kosif-tool/"):
            continue
        import re
        raw = re.sub(r":\d+(?:[-:]\d+)?$", "", ref[len("kosif-tool/"):].split("#", 1)[0])
        p = Path(raw)
        if raw and not p.is_absolute() and ".." not in p.parts and p.suffix in ALL_CODE and (REPO / p).is_file():
            out.append(p.as_posix())
    return sorted(set(out))


def candidates() -> dict:
    return {"power:" + r["id"]: r for r in all_powers() if any_code_proof(r)}


def adapter_spec(pid: str, artifact: dict) -> dict:
    runnable = [p for p in artifact["proofs"] if p.get("verdict") == "passed"]
    kinds = sorted({p["runner"] for p in runnable})
    ran = sum(int(p.get("tests_ran") or 0) for p in runnable)
    return {"script": ".claude/skills/kosif-superpowers/scripts/_black_dragon_power.py",
            "args": [pid, "{artifact}", "--task={task}"],
            "why": f"{pid[6:]}: its cited proof code ran green here ({', '.join(kinds)}; {ran} tests)",
            "power_proof": True,
            "proof_sha256": {p["path"]: p["sha256"] for p in sorted(runnable, key=lambda x: x["path"])}}


def render(adapters: dict, excluded: dict) -> str:
    doc = {"_comment": COMMENT, "schema": SCHEMA,
           "counts": {"candidates": len(adapters) + len(excluded), "included": len(adapters),
                      "excluded": len(excluded)},
           "adapters": adapters, "excluded": excluded}
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def verify_one(pid: str, job: Path, timeout: int) -> tuple[str, int, dict, float]:
    artifact = job / "artifacts" / (pid.replace(":", "_").replace("/", "_") + ".json")
    start = time.monotonic()
    try:
        done = subprocess.run([sys.executable, "-B", str(RUNNER), pid, str(artifact), f"--timeout={timeout}"],
                              cwd=REPO, text=True, capture_output=True, stdin=subprocess.DEVNULL,
                              timeout=timeout * 4 + 120, check=False)
        code = done.returncode
    except subprocess.TimeoutExpired:
        code = 124
    body = json.loads(artifact.read_text(encoding="utf-8")) if artifact.is_file() else {"proofs": []}
    return pid, code, body, time.monotonic() - start


def reason_for(code: int, body: dict, unit_seconds: float, slow: float) -> str | None:
    proofs = body.get("proofs") or []
    if code == 0 and unit_seconds > slow:
        return f"slow: its proof units take over {int(slow)}s here"
    if code == 0:
        return None
    if code == 2:
        why = sorted({p.get("reason", "") for p in proofs if p.get("verdict") == "no-runner"})
        return "refused: " + ("; ".join(why) or body.get("error") or "no runnable proof")
    if code == 124:
        return "timeout: the proof run did not finish"
    failed = [p for p in proofs if p.get("verdict") == "failed"]
    if not failed:
        return "failed: " + str(body.get("error") or "runner error")[:200]
    bits = []
    for p in failed:
        bad = [c["check"] for c in p.get("checks", []) if not c.get("pass")]
        bits.append(f"{p['path']} ({p['runner']}): " + ("; ".join(bad)[:240] or "failed"))
    return "failed: " + " | ".join(sorted(bits))


def build(workers: int, slow: float, timeout: int, job: Path | None) -> int:
    cands = candidates()
    job = job or Path(tempfile.mkdtemp(prefix="black-dragon-power-build-"))
    (job / "artifacts").mkdir(parents=True, exist_ok=True)
    adapters, excluded = {}, {}
    runnable = {}
    for pid, row in cands.items():
        if not power_mod.proof_files(row):
            excluded[pid] = "refused: its only code proofs are shell scripts (not run by this adapter)"
        else:
            runnable[pid] = row
    started = time.monotonic()
    results = {}
    with futures.ThreadPoolExecutor(max_workers=workers) as pool:
        for pid, code, body, secs in pool.map(lambda p: verify_one(p, job, timeout), sorted(runnable)):
            results[pid] = (code, body)
            print(f"{code:>3} {secs:7.1f}s {pid}", file=sys.stderr, flush=True)
    wall = time.monotonic() - started
    unit_secs = {}
    for res in (job / "power-proof-cache").glob("*/result.json"):
        r = json.loads(res.read_text(encoding="utf-8"))
        unit_secs[r["key"]] = float(r.get("seconds") or 0)
    for pid, (code, body) in sorted(results.items()):
        secs = sum(unit_secs.get(p.get("cache_key"), 0) for p in body.get("proofs", []) if p.get("cache_key"))
        why = reason_for(code, body, secs, slow)
        if why is None:
            adapters[pid] = adapter_spec(pid, body)
        else:
            excluded[pid] = why
    OUT.write_text(render(adapters, excluded), encoding="utf-8")
    total_units = sum(unit_secs.values())
    print(json.dumps({"candidates": len(cands), "included": len(adapters), "excluded": len(excluded),
                      "distinct_units": len(unit_secs), "unit_seconds_sum": round(total_units, 1),
                      "wall_seconds": round(wall, 1), "workers": workers, "job": str(job),
                      "out": str(OUT.relative_to(REPO))}, indent=2))
    return 0


def check() -> int:
    if not OUT.is_file():
        print(f"missing {OUT.relative_to(REPO)}; run the build", file=sys.stderr)
        return 1
    text = OUT.read_text(encoding="utf-8")
    doc = json.loads(text)
    adapters, excluded = doc.get("adapters", {}), doc.get("excluded", {})
    problems = []
    if render(adapters, excluded) != text:
        problems.append("file is not in canonical generated form")
    cands = set(candidates())
    listed = set(adapters) | set(excluded)
    if set(adapters) & set(excluded):
        problems.append("power both included and excluded: " + ", ".join(sorted(set(adapters) & set(excluded))[:5]))
    if cands - listed:
        problems.append(f"{len(cands - listed)} new candidate power(s) never verified: "
                        + ", ".join(sorted(cands - listed)[:5]))
    if listed - cands:
        problems.append(f"{len(listed - cands)} listed power(s) no longer cite runnable code: "
                        + ", ".join(sorted(listed - cands)[:5]))
    rows = candidates()
    for pid, spec in sorted(adapters.items()):
        if spec.get("script") != ".claude/skills/kosif-superpowers/scripts/_black_dragon_power.py" or \
                spec.get("args") != [pid, "{artifact}", "--task={task}"]:
            problems.append(f"{pid}: adapter spec is not the generated one")
        for rel, digest in sorted((spec.get("proof_sha256") or {}).items()):
            path = REPO / rel
            if not path.is_file() or power_mod.sha256(path) != digest:
                problems.append(f"{pid}: proof changed since verification: {rel}")
        if pid in rows and set(spec.get("proof_sha256") or {}) - set(power_mod.proof_files(rows[pid])):
            problems.append(f"{pid}: pinned proof no longer cited by the power card")
    for p in problems[:40]:
        print("STALE: " + p, file=sys.stderr)
    if problems:
        print(f"{len(problems)} problem(s); re-run build_black_dragon_power_adapters.py", file=sys.stderr)
        return 1
    print(f"ok: {len(adapters)} power adapters, {len(excluded)} excluded, proofs unchanged")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--slow-limit", type=float, default=120.0)
    ap.add_argument("--timeout", type=int, default=300)
    ap.add_argument("--job", type=Path, default=None, help="scratch job folder (default: a new temp folder)")
    a = ap.parse_args(argv)
    if a.check:
        return check()
    return build(a.workers, a.slow_limit, a.timeout, a.job)


if __name__ == "__main__":
    raise SystemExit(main())
