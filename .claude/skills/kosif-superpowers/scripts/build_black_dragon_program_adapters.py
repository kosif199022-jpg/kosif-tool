#!/usr/bin/env python3
"""Write data/black_dragon_adapters_programs.json: every power card whose program in power_programs/ ran green here.

Usage: build_black_dragon_program_adapters.py [--check] [--family FAMILY ...] [--workers N]

Without --check it runs every program (each in a fresh temp folder) and lists only those that
passed, with each module's sha256. --check is static and fast: it fails when a module changed
(sha256) or a program exists that is neither listed nor excluded, so a stale file cannot pass CI.
--family limits a run to some families and prints results without writing.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import sys
import tempfile
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))
import power_programs as pp  # noqa: E402
import _black_dragon_power_program as runner  # noqa: E402

OUT = SCRIPTS.parent / "data" / "black_dragon_adapters_programs.json"
SCRIPT_REL = ".claude/skills/kosif-superpowers/scripts/_black_dragon_power_program.py"


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _one(pid: str) -> tuple:
    with tempfile.TemporaryDirectory() as tmp:
        r = runner.run_program(pid, Path(tmp) / "w")
    return pid, r.get("ok", False), "; ".join(r.get("problems") or [r.get("error", "")])[:300]


def modules() -> dict:
    return {p.stem: _sha(p) for p in sorted(pp.HERE.glob("*.py")) if not p.name.startswith("_")}


def build(families=None, workers=4) -> dict:
    progs = pp.all_programs()
    cards = pp.card_index()
    ids = sorted(pid for pid in progs if families is None or cards.get(pid, ("",))[0] in families)
    unknown = [pid for pid in ids if pid not in cards]
    ids = [pid for pid in ids if pid in cards]
    with ProcessPoolExecutor(max_workers=workers) as ex:
        results = list(ex.map(_one, ids))
    adapters = {f"power:{pid}": {"script": SCRIPT_REL, "args": [pid, "{artifact}", "--task={task}"],
                                  "power_program": True,
                                  "program": progs[pid][0].name}
                for pid, ok, _ in results if ok}
    excluded = {pid: why for pid, ok, why in results if not ok}
    excluded.update({pid: "not a catalog power id" for pid in unknown})
    return {"_comment": "Generated by build_black_dragon_program_adapters.py. Each power card listed here has a real "
                        "program in scripts/power_programs/ that performs the card's technique on a self-built fixture "
                        "and passed known-answer checks on this machine. Not run on the task text.",
            "adapters": dict(sorted(adapters.items())), "excluded": dict(sorted(excluded.items())),
            "modules": modules(), "runner_sha256": _sha(SCRIPTS / "_black_dragon_power_program.py"),
            "counts": {"programs": len(ids) + len(unknown), "passed": len(adapters), "excluded": len(excluded)}}


def check() -> list:
    if not OUT.is_file():
        return [] if not pp.all_programs() else ["registry missing"]
    data = json.loads(OUT.read_text(encoding="utf-8"))
    problems = []
    if data.get("modules") != modules():
        problems.append("a program module changed; rebuild")
    if data.get("runner_sha256") != _sha(SCRIPTS / "_black_dragon_power_program.py"):
        problems.append("runner changed; rebuild")
    listed = {k.split(":", 1)[1] for k in data.get("adapters", {})} | set(data.get("excluded", {}))
    missing = sorted(set(pp.all_programs()) - listed)
    if missing:
        problems.append(f"{len(missing)} programs not in registry, e.g. {missing[:3]}")
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--family", nargs="*")
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args(argv)
    if a.check:
        problems = check()
        print(json.dumps({"ok": not problems, "problems": problems}, indent=2))
        return 1 if problems else 0
    data = build(set(a.family) if a.family else None, a.workers)
    if a.family:
        print(json.dumps({"counts": data["counts"], "excluded": data["excluded"]}, ensure_ascii=False, indent=2))
        return 0 if not data["excluded"] else 1
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1, sort_keys=False) + "\n", encoding="utf-8")
    print(json.dumps(data["counts"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
