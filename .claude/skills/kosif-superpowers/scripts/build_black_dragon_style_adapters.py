#!/usr/bin/env python3
"""Build data/black_dragon_adapters_styles.json from a REAL run of every catalog style.

Usage:
  build_black_dragon_style_adapters.py [--workers N] [--keep-run]   run every style, write the file
  build_black_dragon_style_adapters.py --check                      fast staleness check, no render
  build_black_dragon_style_adapters.py --check --render             re-run every style, compare output
  build_black_dragon_style_adapters.py --only ID [ID ...]           run some styles, print, write nothing

Every style in catalog/styles.json is run through _black_dragon_style.py (scaffold, offline
headless-Chromium frames, pixel and DOM known-answer checks). Only styles whose run passed
every check here get an adapter entry ("style:<id>"); the others are listed under `excluded`
with the checks that failed. Black Dragon loads the file as a generated registry: the
hand-reviewed black_dragon_adapters.json still wins on any key, and nothing executes without
--execute-adapters.

The file is deterministic (sorted, no times, no machine paths): each entry records the
sha256 of the style's STYLE.json, and the file records the adapter scripts' sha256, so
`--check` can tell, without rendering, when a style or the adapter changed after the run.
`--check` fails too when a catalog style is neither listed nor excluded. Run timings and the
per-style results go to out/black-dragon-styles/last_run.json (gitignored), never to data/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import time
from concurrent import futures
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
SKILL = SCRIPTS.parent
REPO = SKILL.parents[2]
OUT = SKILL / "data" / "black_dragon_adapters_styles.json"
ADAPTER = SCRIPTS / "_black_dragon_style.py"
HELPER = SCRIPTS / "_black_dragon_style_frames.cjs"
RUN_ROOT = REPO / "out" / "black-dragon-styles"
SCHEMA = "kosif.black-dragon.style-adapters.v1"
COMMENT = ("Generated by build_black_dragon_style_adapters.py from a real run on this repository: one entry per "
           "catalog motion style whose run passed every check of _black_dragon_style.py (kosif.py scaffold with the "
           "html-canvas starter, offline headless-Chromium frames at t=1.5/5.0/1.5 s: exact size, not blank, motion "
           "between times, deterministic re-seek, no JS error, DOM known answers). The frame is the shared starter "
           "retitled and sized from the style's STYLE.json: it proves the scaffold/render path, not that the look in "
           "the style's SKILL.md was designed. Styles that failed are under `excluded` with the failed checks. Do not "
           "edit by hand; re-run the builder. The reviewed black_dragon_adapters.json wins on any key.")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rel(path: Path) -> str:
    return path.relative_to(REPO).as_posix()


def catalog_ids() -> list[str]:
    rows = json.loads((REPO / "catalog" / "styles.json").read_text(encoding="utf-8"))
    return sorted(r["id"] for r in rows if isinstance(r, dict) and r.get("id"))


def style_sha(style_id: str) -> str | None:
    p = REPO / "styles" / style_id / "STYLE.json"
    return sha256(p) if p.is_file() else None


def run_one(style_id: str, run_dir: Path, timeout: int) -> dict:
    artifact = run_dir / "artifacts" / f"{style_id}.txt"
    argv = [sys.executable, str(ADAPTER), style_id, str(artifact), "--task=build_black_dragon_style_adapters"]
    started = time.monotonic()
    try:
        done = subprocess.run(argv, cwd=REPO, text=True, capture_output=True, timeout=timeout,
                              stdin=subprocess.DEVNULL, check=False)
        code, err = done.returncode, done.stderr[-300:]
    except subprocess.TimeoutExpired:
        code, err = None, f"timed out after {timeout} s"
    seconds = round(time.monotonic() - started, 3)
    data = {}
    if artifact.is_file():
        try:
            data = json.loads(artifact.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            data = {}
    passed = code == 0 and data.get("passed") is True
    failed = data.get("failed_checks") or ([] if passed else [err.strip() or f"adapter exit {code}"])
    return {"id": style_id, "passed": passed, "exit_code": code, "seconds": seconds,
            "failed_checks": failed, "style_json_sha256": style_sha(style_id),
            "frame_sha256": [f.get("sha256") for f in data.get("frames", [])]}


def run_all(ids: list[str], workers: int, timeout: int, keep: bool) -> tuple[list[dict], dict]:
    run_dir = RUN_ROOT / ("run-" + time.strftime("%Y%m%d-%H%M%S"))
    run_dir.mkdir(parents=True, exist_ok=True)
    started = time.monotonic()
    with futures.ThreadPoolExecutor(max_workers=workers) as pool:
        results = list(pool.map(lambda i: run_one(i, run_dir, timeout), ids))
    total = round(time.monotonic() - started, 3)
    files = sum(1 for p in run_dir.rglob("*") if p.is_file())
    size = sum(p.stat().st_size for p in run_dir.rglob("*") if p.is_file())
    if not keep:
        shutil.rmtree(run_dir)
    meta = {"run_dir": str(run_dir), "kept": keep, "workers": workers, "total_seconds": total,
            "files_written": files, "bytes_written": size}
    return results, meta


def build(results: list[dict]) -> dict:
    script = rel(ADAPTER)
    adapters, excluded = {}, {}
    for r in sorted(results, key=lambda x: x["id"]):
        key = "style:" + r["id"]
        if r["passed"]:
            adapters[key] = {"script": script, "args": [r["id"], "{artifact}", "--task={task}"],
                             "style_render": True, "style_json_sha256": r["style_json_sha256"],
                             "why": "Scaffolds this style (kosif.py scaffold --starter html-canvas) and renders "
                                    "offline Chromium frames checked for size, non-blank pixels, motion, "
                                    "determinism and DOM known answers; verified green when this file was built."}
        else:
            excluded[key] = "failed checks: " + "; ".join(sorted(r["failed_checks"]))[:400]
    return {"_comment": COMMENT, "schema": SCHEMA,
            "adapter_sha256": {rel(ADAPTER): sha256(ADAPTER), rel(HELPER): sha256(HELPER)},
            "counts": {"catalog_styles": len(results), "verified": len(adapters), "excluded": len(excluded)},
            "adapters": adapters, "excluded": excluded}


def dumps(doc: dict) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def static_check(path: Path) -> list[str]:
    """Staleness without rendering: scripts, STYLE.json hashes and catalog coverage."""
    if not path.is_file():
        return [f"{rel(path)} is missing: run the builder"]
    doc = json.loads(path.read_text(encoding="utf-8"))
    problems = []
    for name, digest in (doc.get("adapter_sha256") or {}).items():
        p = REPO / name
        if not p.is_file() or sha256(p) != digest:
            problems.append(f"adapter script changed since the run: {name}")
    if set(doc.get("adapter_sha256") or {}) != {rel(ADAPTER), rel(HELPER)}:
        problems.append("adapter_sha256 does not cover the adapter and its helper")
    ids = set(catalog_ids())
    listed = {k.split(":", 1)[1] for k in doc.get("adapters", {})}
    excluded = {k.split(":", 1)[1] for k in doc.get("excluded", {})}
    for missing in sorted(ids - listed - excluded):
        problems.append(f"catalog style not covered by the run: {missing}")
    for gone in sorted((listed | excluded) - ids):
        problems.append(f"style no longer in the catalog: {gone}")
    for key, spec in doc.get("adapters", {}).items():
        sid = key.split(":", 1)[1]
        if spec.get("script") != rel(ADAPTER) or spec.get("args") != [sid, "{artifact}", "--task={task}"]:
            problems.append(f"unexpected adapter spec: {key}")
        if sid in ids and spec.get("style_json_sha256") != style_sha(sid):
            problems.append(f"STYLE.json changed since the run: {sid}")
    return problems


def write_summary(results: list[dict], meta: dict) -> Path:
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    summary = RUN_ROOT / "last_run.json"
    secs = sorted(r["seconds"] for r in results)
    meta = dict(meta, styles=len(results), passed=sum(r["passed"] for r in results),
                failed=sum(not r["passed"] for r in results),
                seconds_per_style={"min": secs[0], "median": secs[len(secs) // 2], "max": secs[-1]} if secs else {})
    summary.write_text(json.dumps({"meta": meta, "results": results}, ensure_ascii=False, indent=2) + "\n",
                       encoding="utf-8")
    return summary


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the file is stale (no render unless --render)")
    ap.add_argument("--render", action="store_true", help="with --check: re-run every style and compare")
    ap.add_argument("--only", nargs="+", metavar="ID", help="run these styles only; writes nothing")
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--timeout", type=int, default=120, help="seconds per style")
    ap.add_argument("--keep-run", action="store_true", help="keep the run's artifacts under out/")
    ap.add_argument("--out", type=Path, default=OUT, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if not 1 <= args.workers <= 16:
        ap.error("--workers must be 1..16")
    if args.check and not args.render:
        problems = static_check(args.out)
        print(json.dumps({"check": "static", "ok": not problems, "problems": problems}, ensure_ascii=False, indent=2))
        return 1 if problems else 0
    ids = args.only or catalog_ids()
    unknown = sorted(set(ids) - set(catalog_ids()))
    if unknown:
        ap.error("not in catalog/styles.json: " + ", ".join(unknown))
    results, meta = run_all(ids, args.workers, args.timeout, args.keep_run)
    summary = write_summary(results, meta)
    report = {"styles": len(results), "verified": sum(r["passed"] for r in results),
              "excluded": {r["id"]: r["failed_checks"] for r in results if not r["passed"]},
              "total_seconds": meta["total_seconds"], "summary": str(summary)}
    if args.only:
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0 if not report["excluded"] else 1
    text = dumps(build(results))
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        report["ok"] = current == text
        print(json.dumps(report, ensure_ascii=False, indent=2))
        return 0 if report["ok"] else 1
    args.out.write_text(text, encoding="utf-8")
    report["wrote"] = str(args.out)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
