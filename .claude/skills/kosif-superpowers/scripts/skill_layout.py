#!/usr/bin/env python3
"""Skill layout: one section per reference file / خريطة ترتيب ملفات المهارة.

data/skill_layout.json puts every file under references/ (plus the entry documents) into exactly one section, in
reading order. This script builds the readable map references/LAYOUT.md from it and checks it like a trial balance:
every file on disk is in one section, and every listed file exists.

    python3 scripts/skill_layout.py build           # write references/LAYOUT.md
    python3 scripts/skill_layout.py check           # exit 1 on an unlisted, doubly listed or missing file, or a stale LAYOUT.md
    python3 scripts/skill_layout.py where <name>    # which section holds a file (substring match)
    python3 scripts/skill_layout.py moves           # the git mv commands that would move each section to its planned folder (a deferred, separate step)
    python3 scripts/skill_layout.py --self-test

check_skill.py runs the same check as its "layout" check. Python 3.8+ standard library only; it never moves a file.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SK = HERE.parent
LAYOUT_JSON = SK / "data" / "skill_layout.json"
LAYOUT_MD = SK / "references" / "LAYOUT.md"
SCANNED = ("*.md", "*.html")


def load(path: Path = LAYOUT_JSON) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def disk_files(root: Path = SK) -> list:
    """Every reference file the layout must place (relative to the skill folder, POSIX)."""
    refs = root / "references"
    out = []
    if refs.is_dir():
        for pat in SCANNED:
            out += [p.relative_to(root).as_posix() for p in refs.rglob(pat) if p.is_file()]
    return sorted(set(out))


def assign(layout: dict, files: list) -> dict:
    """{file: [section ids]} for the given files, from explicit lists and globs."""
    got = {f: [] for f in files}
    for s in layout["sections"]:
        for f in files:
            if f in s.get("files", []) or any(fnmatch.fnmatchcase(f, g) for g in s.get("globs", [])):
                got[f].append(s["id"])
    return got


def render(layout: dict, root: Path = SK) -> str:
    files = disk_files(root)
    got = assign(layout, files)
    L = ["# ترتيب المهارة — KOSIF Superpowers layout", "",
         "Generated by `scripts/skill_layout.py build` from `data/skill_layout.json`; do not edit by hand. "
         "Every reference file sits in exactly one section, in reading order; `check_skill.py` fails when one does not. "
         "خريطة واحدة تقول أين يعيش كل ملف ولماذا.", "",
         "## الفهرس / contents", ""]
    secs = layout["sections"]
    for n, s in enumerate(secs, 1):
        L.append(f"- [{n}. {s['ar']} / {s['en']}](#{n}-{slug(s['ar'] + ' / ' + s['en'])})")
    L += ["", "## القواعد / rules", ""] + [f"- {r}" for r in layout.get("rules", [])]
    for n, s in enumerate(secs, 1):
        members = list(s.get("files", []))
        members += [f for f in files if s["id"] in got.get(f, []) and f not in members]
        L += ["", f"## {n}. {s['ar']} / {s['en']}", "", s["about"], ""]
        L.append(f"`{s['id']}` · {len(members)} file(s)" + (f" · planned folder `{s['target']}/`" if s.get("target") else ""))
        L.append("")
        pinned = set(layout.get("pinned", []))
        for f in members:
            link = Path(f).relative_to("references").as_posix() if f.startswith("references/") else "../" + f
            L.append(f"- [{f}]({link})" + (" · pinned (fixed path)" if f in pinned else ""))
    return "\n".join(L) + "\n"


def slug(title: str) -> str:
    import unicodedata
    t = title.strip().lower()
    return "".join(c for c in t if c in " -_" or unicodedata.category(c)[0] in "LMN").replace(" ", "-")


def problems(layout: dict = None, root: Path = SK, md_path: Path = None) -> list:
    """[(level, message)]; errors make the check fail."""
    layout = layout if layout is not None else load()
    md_path = md_path if md_path is not None else root / "references" / "LAYOUT.md"
    out = []
    ids = [s["id"] for s in layout["sections"]]
    if len(ids) != len(set(ids)):
        out.append(("error", "data/skill_layout.json has duplicate section ids"))
    files = disk_files(root)
    for f, secs in assign(layout, files).items():
        if not secs:
            out.append(("error", f"{f} has no section in data/skill_layout.json (add it to exactly one)"))
        elif len(secs) > 1:
            out.append(("error", f"{f} is in {len(secs)} sections ({', '.join(secs)}); keep one"))
    for f in layout.get("pinned", []):
        if not (root / f).is_file():
            out.append(("error", f"data/skill_layout.json pins {f}, which does not exist"))
    for s in layout["sections"]:
        for f in s.get("files", []):
            if not (root / f).is_file():
                out.append(("error", f"data/skill_layout.json section {s['id']!r} lists {f}, which does not exist"))
    if not md_path.is_file():
        out.append(("error", "references/LAYOUT.md is missing: run python3 scripts/skill_layout.py build"))
    elif md_path.read_text(encoding="utf-8") != render(layout, root):
        out.append(("error", "references/LAYOUT.md is stale: run python3 scripts/skill_layout.py build"))
    out.append(("info", f"layout: {len(files)} reference file(s) in {len(ids)} section(s)"))
    return out


def planned_moves(layout: dict, root: Path = SK) -> list:
    """[(src, dst)] for files whose section has a target folder they are not yet in."""
    moves, pinned = [], set(layout.get("pinned", []))
    got = assign(layout, disk_files(root))
    for s in layout["sections"]:
        t = s.get("target")
        if not t:
            continue
        for f, secs in got.items():
            if secs == [s["id"]] and f not in pinned and not f.startswith(t + "/"):
                moves.append((f, f"{t}/{Path(f).name}"))
    return moves


def self_test() -> int:
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        (root / "references" / "protocol").mkdir(parents=True)
        for f in ("references/a.md", "references/b.md", "references/protocol/A1-x.md"):
            (root / f).write_text("# x\n", encoding="utf-8")
        lay = {"sections": [{"id": "one", "ar": "واحد", "en": "One", "about": "x", "target": "references/one", "files": ["references/a.md"], "globs": []},
                            {"id": "proto", "ar": "بروتوكول", "en": "Protocol", "about": "y", "target": None, "files": [], "globs": ["references/protocol/*"]}]}
        errs = [m for lv, m in problems(lay, root) if lv == "error"]
        assert any("references/b.md has no section" in m for m in errs), errs
        assert any("LAYOUT.md is missing" in m for m in errs), errs
        lay["sections"][0]["files"].append("references/b.md")
        (root / "references" / "LAYOUT.md").write_text("old", encoding="utf-8")
        lay["sections"][0]["files"].append("references/LAYOUT.md")
        assert any("stale" in m for lv, m in problems(lay, root) if lv == "error")
        (root / "references" / "LAYOUT.md").write_text(render(lay, root), encoding="utf-8")
        assert not [m for lv, m in problems(lay, root) if lv == "error"], problems(lay, root)
        lay["sections"][1]["files"].append("references/a.md")
        assert any("2 sections" in m for lv, m in problems(lay, root) if lv == "error")
        lay["sections"][1]["files"] = ["references/gone.md"]
        assert any("gone.md, which does not exist" in m for lv, m in problems(lay, root) if lv == "error")
        lay["sections"][1]["files"] = []
        mv = planned_moves(lay, root)
        assert ("references/a.md", "references/one/a.md") in mv and all(not s.startswith("references/protocol") for s, _d in mv), mv
    print("skill_layout self-test: OK")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--self-test", action="store_true")
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("build")
    sub.add_parser("check")
    w = sub.add_parser("where"); w.add_argument("name")
    sub.add_parser("moves")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    layout = load()
    if a.cmd == "build":
        LAYOUT_MD.write_text(render(layout), encoding="utf-8")
        print(f"wrote {LAYOUT_MD.relative_to(SK).as_posix()}")
        return 0
    if a.cmd == "where":
        got = assign(layout, disk_files())
        hits = [(f, s) for f, s in got.items() if a.name.lower() in f.lower()]
        for f, s in hits:
            print(f"{f}\t{', '.join(s) or '— no section'}")
        return 0 if hits else 1
    if a.cmd == "moves":
        mv = planned_moves(layout)
        for src, dst in mv:
            print(f"git mv {src} {dst}")
        print(f"# {len(mv)} move(s); after moving, update links and run check_skill.py", file=sys.stderr)
        return 0
    probs = problems(layout)
    for lv, m in probs:
        print(f"{lv.upper():5} {m}")
    return 1 if any(lv == "error" for lv, _m in probs) else 0


if __name__ == "__main__":
    sys.exit(main())
