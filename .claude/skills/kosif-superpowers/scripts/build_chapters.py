#!/usr/bin/env python3
"""Generate the chapter of every general (non-motion) power family / ولّد فصول العائلات العامة.

Reads data/powers/<family>.json and writes references/powers/<family>.md in the
same shape as the hand-made motion chapters: title AR — EN, summary block with
badge counts, badge legend, contents by section, one block per power
(what / when / how / params / install / license / proof / source) and a footer.

The 30 motion chapters are never touched. A chapter is only overwritten when it
carries the generated marker (or with --force). Output is deterministic, so a
second run changes nothing.

  python3 build_chapters.py              # write every general chapter that changed
  python3 build_chapters.py --check      # exit 1 if any chapter is missing or stale
  python3 build_chapters.py --family thinking-core
  python3 build_chapters.py --prune      # also delete generated chapters whose JSON is gone

Python 3.8+ standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import powers as P  # noqa: E402  (same folder)

ROOT = P.ROOT
DATA = P.DATA / "powers"
OUT = P.CHAPTERS
REFS = ROOT / "references"
MARKER = "<!-- generated by scripts/build_chapters.py"

# The original motion families: their chapters are hand-made or aggregated elsewhere.
MOTION_STEMS = frozenset((
    "3d-spatial", "ai-generation", "audio-sync-captions", "brand-logo-identity", "camera-composition-layout",
    "characters-rigs", "charts-data-infographic", "color-palette-grading", "diagrams-explainers-code",
    "easing-timing-rhythm", "engines-render-pipeline", "formats-platforms", "hand-drawn-draw-on", "light-glow-bloom",
    "maps-geo", "music-beat-sound", "other", "particles-fluids-physics", "photo-video-footage", "pixel-retro-stylized",
    "qa-verification", "shapes-morph-geometry", "story-direction-ideas", "texture-material", "transitions-cuts",
    "typography-arabic", "typography-latin", "ui-product-device", "video-download", "voice-tts",
))

LABEL = {
    "proven": "✅ مُثبت هنا / proven here",
    "ready": "🟢 جاهز / ready",
    "install": "📦 بأمر تثبيت / one install",
    "key": "🔑 مفتاح أو خدمة / needs key or service",
    "seen": "👁 شوهد في فيديو / seen in a reference video",
    "documented": "📄 موصوف / documented only",
    "idea": "💡 فكرة / idea",
}
LEGEND = ("**الحالة / status:** ✅ مُثبت (شُغّل فعلًا وله مسار دليل) · 🟢 جاهز (كود موجود يعمل بما هو متاح عادة) · "
          "📦 بأمر تثبيت واحد · 🔑 يحتاج مفتاحًا أو حسابًا أو موصلًا · 👁 شوهد في فيديو مرجعي (للموشن فقط) · "
          "📄 طريقة موثقة · 💡 فكرة. الشارة هي أدنى مستوى صادق — the badge is the lowest level that is true.")
PROOF_NOTE = ("مسارات الدليل نسبية إلى `/home/user/`؛ و`session-<date>:<file>#<section>` تشير إلى تشغيل موثق في جلسة سابقة؛ "
              "و`owner-upload:` إلى ملف داخل أرشيف أرسله المالك. Proof paths are relative to `/home/user/`.")


def load_family(path: Path):
    try:
        rows = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        return None, f"{path.name}: {e}"
    if not isinstance(rows, list):
        return None, f"{path.name}: expected a JSON list"
    return [r for r in rows if isinstance(r, dict)], ""


def family_domain(rows) -> str:
    dom = Counter((r.get("domain") or P.DEFAULT_DOMAIN) for r in rows)
    return dom.most_common(1)[0][0] if dom else P.DEFAULT_DOMAIN


def general_families():
    """[(stem, path, rows)] for every family JSON whose records are not motion."""
    out, errors = [], []
    for path in sorted(DATA.glob("*.json")):
        stem = path.stem
        if stem in MOTION_STEMS:
            continue
        rows, err = load_family(path)
        if err:
            errors.append(err)
            continue
        if not rows or family_domain(rows) == P.DEFAULT_DOMAIN:
            continue
        out.append((stem, path, rows))
    return out, errors


def _unlink(seg: str) -> str:
    """Escape '[x](y)' outside code unless y is a web URL, so quoted patterns never become dead links."""
    return re.sub(r"\]\((?!https?://)", r"]\\(", seg)


def clean(text) -> str:
    """One-bullet text: keep newlines but indent them so they stay inside the list item."""
    s = str(text if text is not None else "").strip()
    parts = s.split("`")
    s = "`".join(_unlink(x) if i % 2 == 0 else x for i, x in enumerate(parts))  # odd parts are code spans
    return s.replace("\r\n", "\n").replace("\n", "\n  ")


def related_refs(stem: str, prefix: str, rows) -> list:
    """Narrative references that mention this family (by source field, stem or ID)."""
    names = set()
    for r in rows:
        for m in re.findall(r"references/([A-Za-z0-9_.-]+\.md)", str(r.get("source") or "")):
            names.add(m)
    id_re = re.compile(r"\b%s-\d{2,3}\b" % re.escape(prefix)) if prefix else None
    if REFS.is_dir():
        for f in sorted(REFS.glob("*.md")):
            try:
                txt = f.read_text(encoding="utf-8")
            except OSError:
                continue
            if stem in txt or (id_re and id_re.search(txt)):
                names.add(f.name)
    return sorted(n for n in names if (REFS / n).is_file())


def render(stem: str, rows) -> str:
    domain = family_domain(rows)
    meta = P.FAMILY_META.get(stem)
    prefix = meta[0] if meta else (Counter(P.prefix_of(r) for r in rows).most_common(1)[0][0] if rows else "")
    t_ar, t_en = P.family_title(stem)
    s_ar, s_en = (meta[4], meta[5]) if meta else ("", "")
    d_ar, d_en = P.DOMAINS.get(domain, (domain, domain))
    st = Counter(r.get("status") for r in rows)
    L = [f"# {t_ar} — {t_en}",
         f"{MARKER} from data/powers/{stem}.json; edit the JSON and re-run, not this file -->",
         ""]
    if s_ar or s_en:
        L.append(f"> **قوتك هنا / what this gives you:** {s_ar} — {s_en}".replace(" —  — ", " — ").rstrip(" —"))
    proven = [r for r in rows if r.get("status") == "proven" and r.get("proof")]
    if proven:
        ev = " · ".join(f"**{r.get('id')}** {r.get('name_en', '')} (`{r['proof'][0]}`)" for r in proven[:2])
        L.append(f"> **أقوى دليل / strongest evidence:** {ev}")
    else:
        best = next((s for s in P.STATUSES if st.get(s)), "documented")
        L.append(f"> **أقوى دليل / strongest evidence:** لا قوة مثبتة بعد في هذه العائلة — no ✅ power yet; "
                 f"the strongest badge here is {P.BADGE.get(best, '')} {best}.")
    counts = " · ".join(f"{P.BADGE[s]} {st.get(s, 0)}" for s in P.STATUSES)
    L.append(f"> **{len(rows)} powers follow** — {counts}.")
    L += ["", LEGEND, PROOF_NOTE, ""]
    L.append(f"**المجال / domain:** {d_ar} — {d_en} · **البادئة / prefix:** `{prefix}` · "
             f"**البيانات / data:** `data/powers/{stem}.json` · **بحث / search:** `python3 scripts/powers.py family {stem}`")
    refs = related_refs(stem, prefix, rows)
    if refs:
        L.append("**مراجع ذات صلة / related references:** " + " · ".join(f"[{n}](../{n})" for n in refs))
    sections = OrderedDict()
    for r in rows:
        sections.setdefault((r.get("section") or "عام — General").strip(), []).append(r)
    L += ["", "## الفهرس / contents", ""]
    for sec, rs in sections.items():
        rng = rs[0].get("id") if len(rs) == 1 else f"{rs[0].get('id')} … {rs[-1].get('id')}"
        L.append(f"- **{sec}** — {rng} ({len(rs)})")
    L.append("- المصادر والرخص / sources & licences")
    for sec, rs in sections.items():
        L += ["", f"## {sec}", ""]
        for r in rs:
            L.append(f"#### {r.get('id')} · {r.get('name_ar', '')} · {r.get('name_en', '')} · "
                     f"{LABEL.get(r.get('status'), r.get('status', ''))}")
            L.append(f"- **ماذا / what:** {clean(r.get('what'))}")
            if r.get("when"):
                L.append(f"- **متى أستخدمها / when:** {clean(r.get('when'))}")
            how = clean(r.get("how"))
            params = clean(r.get("params"))
            if how or params:
                L.append(f"- **كيف / how:** {how}" + (f" **أرقام / params:** {params}" if params else ""))
            if r.get("install"):
                L.append(f"- **تثبيت / install:** `{str(r['install']).strip()}`")
            if r.get("license"):
                L.append(f"- **الرخصة / license:** {clean(r.get('license'))}")
            proof = [str(p) for p in (r.get("proof") or [])]
            L.append("- **الدليل / proof:** " + (" · ".join(f"`{p}`" for p in proof) if proof else "— (لا دليل تشغيل بعد / no run proof yet)"))
            if r.get("styles"):
                L.append("- **أساليب / styles:** " + " · ".join(f"`{s}`" for s in r["styles"]))
            if r.get("source"):
                L.append(f"- **المصدر / source:** {clean(r.get('source'))}")
            L.append("")
        if L[-1] == "":
            L.pop()
    lic = Counter((str(r.get("license") or "").strip() or "—") for r in rows)
    L += ["", "## المصادر والرخص / sources & licences", ""]
    L.append("- الرخص / licences: " + " · ".join(f"{k} ({v})" for k, v in sorted(lic.items(), key=lambda kv: (-kv[1], kv[0]))))
    L.append("- الأفكار مكتوبة بكلماتنا مع رابط المصدر؛ لا يُنسخ نص طرف ثالث طويل. Ideas are paraphrased with a link to the "
             "source; no long third-party text is copied. `—` = no licence recorded (own method or own wording).")
    L += ["", "---",
          f"_مولَّد آليًا من `data/powers/{stem}.json` بواسطة `scripts/build_chapters.py` — Generated; edit the JSON, then run "
          f"`python3 scripts/build_chapters.py` (`--check` fails while this file is stale)._", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate references/powers/<family>.md for general (non-motion) families")
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated chapter is missing or out of date")
    ap.add_argument("--family", help="only this family stem")
    ap.add_argument("--force", action="store_true", help="overwrite a chapter even without the generated marker")
    ap.add_argument("--prune", action="store_true", help="delete generated chapters whose JSON no longer exists")
    ap.add_argument("--out", metavar="DIR", help="write chapters here instead of references/powers (for tests)")
    ap.add_argument("-q", "--quiet", action="store_true")
    a = ap.parse_args(argv)
    out_dir = Path(a.out) if a.out else OUT
    fams, errors = general_families()
    for e in errors:
        print(f"warning: {e}", file=sys.stderr)
    if a.family:
        fams = [f for f in fams if f[0] == a.family]
        if not fams:
            print(f"no general family named {a.family}", file=sys.stderr)
            return 2
    stale, wrote, same, refused = [], [], [], []
    for stem, _path, rows in fams:
        out = out_dir / f"{stem}.md"
        text = render(stem, rows)
        old = out.read_text(encoding="utf-8") if out.is_file() else None
        if old == text:
            same.append(stem)
            continue
        if old is not None and MARKER not in old and not a.force:
            refused.append(stem)
            continue
        if a.check:
            stale.append(stem + (" (missing)" if old is None else " (stale)"))
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        wrote.append(stem)
    # generated chapters whose JSON is gone
    live = {f[0] for f in fams} if not a.family else set()
    orphans = []
    if not a.family and out_dir.is_dir():
        for f in sorted(out_dir.glob("*.md")):
            if f.stem in live or f.stem in MOTION_STEMS:
                continue
            try:
                if MARKER in f.read_text(encoding="utf-8"):
                    orphans.append(f)
            except OSError:
                pass
    for f in orphans:
        if a.prune and not a.check:
            f.unlink()
            print(f"pruned {f.name} (no JSON)")
        else:
            stale.append(f"{f.stem} (generated chapter without JSON; run --prune)")
    for stem in refused:
        print(f"refused: references/powers/{stem}.md exists without the generated marker (use --force)", file=sys.stderr)
    if a.check:
        if stale or refused:
            for s in stale:
                print(f"out of date: references/powers/{s.split(' ')[0]}.md — {s}")
            print(f"build_chapters --check: {len(stale) + len(refused)} problem(s); run python3 scripts/build_chapters.py")
            return 1
        if not a.quiet:
            print(f"build_chapters --check: {len(same)} general chapter(s) up to date" + ("" if fams else " (no general families yet)"))
        return 0
    if not a.quiet:
        for s in wrote:
            print(f"wrote {out_dir / (s + '.md')}" if a.out else f"wrote references/powers/{s}.md")
        print(f"build_chapters: {len(wrote)} written · {len(same)} unchanged · {len(refused)} refused · "
              f"{len(fams)} general famil{'y' if len(fams) == 1 else 'ies'} · motion chapters untouched")
    return 1 if refused else 0


if __name__ == "__main__":
    sys.exit(main())
