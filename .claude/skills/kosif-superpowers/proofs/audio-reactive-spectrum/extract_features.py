#!/usr/bin/env python3
"""Per-frame audio features for a seekable film (pre-baked, so every frame is a pure function of t).

For each video frame f (t = f / fps) a Hann window of WIN samples centred on t gives:
  rms   : loudness of the 1/fps slice around t, dB mapped [p95 - 30, p95] -> 0..1
  bands : 16 log-spaced bands (70 Hz - 9 kHz), band power in dB, each band mapped
          [p99 - 42 dB, p99] -> 0..1 (per-band normalisation so treble is visible too)
and an attack/release envelope (attack 0.65, release 0.20 per frame) applied here,
not in the page, so seeking to any frame needs no history.

usage: python extract_features.py voice.wav features.json features.js [fps=30] [win=4096]
"""
import json
import sys

import numpy as np
import soundfile as sf

src, out_json, out_js = sys.argv[1:4]
FPS = int(sys.argv[4]) if len(sys.argv) > 4 else 30
WIN = int(sys.argv[5]) if len(sys.argv) > 5 else 4096
N_BANDS, F_LO, F_HI = 16, 70.0, 9000.0
ATTACK, RELEASE = 0.65, 0.20

y, sr = sf.read(src, always_2d=True)
y = y.mean(axis=1).astype(np.float64)
dur = len(y) / sr
n_frames = int(round(dur * FPS))
pad = np.pad(y, (WIN, WIN))
hann = np.hanning(WIN)
freqs = np.fft.rfftfreq(WIN, 1 / sr)
edges = np.geomspace(F_LO, F_HI, N_BANDS + 1)
band_idx = [np.where((freqs >= edges[k]) & (freqs < edges[k + 1]))[0] for k in range(N_BANDS)]
for k, idx in enumerate(band_idx):  # bass bands narrower than one bin: take the nearest bin
    if len(idx) == 0:
        band_idx[k] = np.array([int(np.argmin(np.abs(freqs - np.sqrt(edges[k] * edges[k + 1]))))])

slice_len = int(sr / FPS)
rms_db, band_db = [], []
for f in range(n_frames):
    c = int(round(f / FPS * sr)) + WIN
    seg = pad[c - WIN // 2:c + WIN // 2] * hann
    p = np.abs(np.fft.rfft(seg)) ** 2
    band_db.append([10 * np.log10(np.mean(p[idx]) + 1e-12) for idx in band_idx])
    s = pad[c - slice_len // 2:c + slice_len // 2]
    rms_db.append(20 * np.log10(np.sqrt(np.mean(s ** 2)) + 1e-9))
rms_db, band_db = np.array(rms_db), np.array(band_db)

ref = np.percentile(rms_db, 95)
rms = np.clip((rms_db - (ref - 30)) / 30, 0, 1) ** 1.5
top = np.percentile(band_db, 99, axis=0)
bands = np.clip((band_db - (top - 42)) / 42, 0, 1) ** 1.3


def envelope(x):
    out, e = np.zeros_like(x), np.zeros(x.shape[1:]) if x.ndim > 1 else 0.0
    for i in range(len(x)):
        a = np.where(x[i] > e, ATTACK, RELEASE)
        e = e + a * (x[i] - e)
        out[i] = e
    return out


rms_env, bands_env = envelope(rms), envelope(bands)
data = {
    "fps": FPS, "duration": round(dur, 3), "frames": n_frames, "sr": sr, "window": WIN,
    "bands_hz": [round(float(e), 1) for e in edges],
    "note": "rms/bands are 0..1 after attack/release; index = round(t * fps)",
    "rms": [round(float(v), 3) for v in rms_env],
    "bands": [[round(float(v), 3) for v in row] for row in bands_env],
}
json.dump(data, open(out_json, "w"), separators=(",", ":"))
with open(out_js, "w") as fh:
    fh.write("// Generated by extract_features.py (same data as features.json) so the page opens from file://\n")
    fh.write("window.KOSIF_FEATURES = " + json.dumps(data, separators=(",", ":")) + ";\n")
loud = rms_env > 0.3
print(f"{n_frames} frames @ {FPS} fps, {dur:.3f} s, sr {sr}, window {WIN} ({1000 * WIN / sr:.0f} ms)")
print(f"rms env: mean {rms_env.mean():.2f}, max {rms_env.max():.2f}, frames > 0.3: {loud.sum()}")
print("band means:", " ".join(f"{v:.2f}" for v in bands_env.mean(axis=0)))
