def write_scene(path, rec, runs, metrics, verdict=None):
    data = scene_data(rec, runs, metrics, verdict)
    html = (PAGE.replace("__TITLE__", "KOSIF Matrices · " + rec["title_en"])
            .replace("__FONT__", _b64(FONT.read_bytes()) if FONT.exists() else "")
            .replace("__HARNESS__", (ATLAS / "atlas_harness.js").read_text(encoding="utf-8").replace("</script", "<\\/script"))
            .replace("__SOUND__", (ATLAS / "atlas_sound.js").read_text(encoding="utf-8").replace("</script", "<\\/script"))
            .replace("__DATA__", json.dumps(data, separators=(",", ":"))))
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(html, encoding="utf-8")
    return {"out": str(p), "bytes": p.stat().st_size, "frames": data["frames"], "conditions": [c["key"] for c in data["conditions"]]}
